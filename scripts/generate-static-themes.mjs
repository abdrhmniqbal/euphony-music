/**
 * generate-static-themes.mjs
 *
 * Reads src/global.css and generates src/modules/ui/static-themes.ts
 * CSS is the single source of truth for theme colors.
 *
 * Usage: node scripts/generate-static-themes.mjs
 */

import { readFileSync, writeFileSync } from "node:fs"
import { resolve, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, "..")
const CSS_PATH = resolve(ROOT, "src/global.css")
const OUT_PATH = resolve(ROOT, "src/modules/ui/static-themes.ts")

// --- oklch → hex conversion ---

function oklchToLinearSrgb(L, C, Hdeg) {
  const Hrad = (Hdeg * Math.PI) / 180
  const a = C * Math.cos(Hrad)
  const b = C * Math.sin(Hrad)

  // oklab → linear sRGB
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b
  const s_ = L - 0.0894841775 * a - 1.291485548 * b

  const l = l_ ** 3
  const m = m_ ** 3
  const s = s_ ** 3

  let r = +4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
  let g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
  let bl = -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s

  return [r, g, bl]
}

function linearToGamma(c) {
  return c >= 0.0031308 ? 1.055 * c ** (1 / 2.4) - 0.055 : 12.92 * c
}

function clamp01(v) {
  return Math.max(0, Math.min(1, v))
}

function oklchToHex(L, C, H, A) {
  const [rLin, gLin, bLin] = oklchToLinearSrgb(L, C, H)
  const r = Math.round(clamp01(linearToGamma(rLin)) * 255)
  const g = Math.round(clamp01(linearToGamma(gLin)) * 255)
  const b = Math.round(clamp01(linearToGamma(bLin)) * 255)

  if (A !== undefined && A < 1) {
    return `rgba(${r}, ${g}, ${b}, ${+A.toFixed(4)})`
  }

  return `#${r.toString(16).padStart(2, "0")}${g.toString(16).padStart(2, "0")}${b.toString(16).padStart(2, "0")}`
}

function parseOklch(value) {
  const match = value.match(
    /oklch\(\s*([\d.]+)%?\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+)%?)?\s*\)/
  )
  if (!match) return null

  let L = parseFloat(match[1])
  if (value.includes(`${match[1]}%`)) L = L / 100

  const C = parseFloat(match[2])
  const H = parseFloat(match[3])

  let A
  if (match[4] !== undefined) {
    A = parseFloat(match[4])
    if (value.includes(`${match[4]}%`)) A = A / 100
  }

  return oklchToHex(L, C, H, A)
}

// --- CSS parsing ---

function parseSharedVars(css) {
  const vars = {}
  // Match @theme inline static { ... } — shared primitive colors
  const themeMatch = css.match(/@theme\s+inline\s+static\s*\{([\s\S]*?)\n\s*\}/)
  if (themeMatch) {
    const block = themeMatch[1]
    const re = /--([\w-]+)\s*:\s*([^;]+);/g
    let m
    while ((m = re.exec(block)) !== null) {
      vars[m[1]] = m[2].trim()
    }
  }
  return vars
}

function parseThemeBlocks(css) {
  const themes = {}
  const blockRe = /@variant\s+theme-(\w[\w-]*)-(light|dark)\s*\{([\s\S]*?)\n\s*\}/g
  let m

  while ((m = blockRe.exec(css)) !== null) {
    const id = m[1]
    const mode = m[2]
    const block = m[3]

    if (!themes[id]) themes[id] = {}

    const vars = {}
    const varRe = /--([\w-]+)\s*:\s*([^;]+);/g
    let vm
    while ((vm = varRe.exec(block)) !== null) {
      vars[vm[1]] = vm[2].trim()
    }

    themes[id][mode] = vars
  }

  return themes
}

function resolveValue(rawValue, localVars, sharedVars) {
  // Handle var() references
  const varMatch = rawValue.match(/^var\(--([\w-]+)\)$/)
  if (varMatch) {
    const refName = varMatch[1]
    if (localVars[refName] !== undefined) {
      return resolveValue(localVars[refName], localVars, sharedVars)
    }
    if (sharedVars[refName] !== undefined) {
      return resolveValue(sharedVars[refName], localVars, sharedVars)
    }
    return rawValue
  }

  // Handle oklch()
  if (rawValue.startsWith("oklch(")) {
    const hex = parseOklch(rawValue)
    if (hex) return hex
  }

  // Already hex or other literal
  return rawValue
}

// --- ThemeColors tokens to extract ---

const THEME_TOKENS = [
  "background",
  "foreground",
  "surface",
  "default",
  "muted",
  "accent",
  "border",
  "link",
  "danger",
  "success",
  "warning",
  "accent-foreground",
  "backdrop",
]

const RAINBOW_COUNT = 16

function toCamelCase(kebab) {
  return kebab.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
}

// --- Generate ---

function generate() {
  const css = readFileSync(CSS_PATH, "utf-8")
  const sharedVars = parseSharedVars(css)
  const themes = parseThemeBlocks(css)

  const lines = []
  lines.push("// AUTO-GENERATED by scripts/generate-static-themes.mjs — DO NOT EDIT")
  lines.push("// Source of truth: src/global.css")
  lines.push("")
  lines.push("export interface ThemeColors {")
  for (const token of THEME_TOKENS) {
    lines.push(`  ${toCamelCase(token)}: string`)
  }
  lines.push('  rainbow: string[]')
  lines.push("}")
  lines.push("")

  const themeIds = Object.keys(themes).sort((a, b) => {
    // default first, then alphabetical
    if (a === "default") return -1
    if (b === "default") return 1
    return a.localeCompare(b)
  })

  lines.push(`export const STATIC_THEMES: Record<string, { light: ThemeColors; dark: ThemeColors }> = {`)

  for (const id of themeIds) {
    const modes = themes[id]
    lines.push(`  ${JSON.stringify(id)}: {`)

    for (const mode of ["light", "dark"]) {
      const vars = modes[mode]
      if (!vars) continue

      lines.push(`    ${mode}: {`)

      for (const token of THEME_TOKENS) {
        const raw = vars[token]
        if (raw === undefined) {
          console.warn(`  ⚠ ${id}/${mode}: missing --${token}`)
          continue
        }
        const resolved = resolveValue(raw, vars, sharedVars)
        const key = toCamelCase(token)
        lines.push(`      ${key}: ${JSON.stringify(resolved)},`)
      }

      // Rainbow
      const rainbow = []
      for (let i = 0; i < RAINBOW_COUNT; i++) {
        const raw = vars[`rainbow-${i}`]
        if (raw) {
          rainbow.push(resolveValue(raw, vars, sharedVars))
        }
      }
      lines.push(`      rainbow: [`)
      for (const c of rainbow) {
        lines.push(`        ${JSON.stringify(c)},`)
      }
      lines.push(`      ],`)

      lines.push(`    },`)
    }

    lines.push(`  },`)
  }

  lines.push("}")
  lines.push("")

  writeFileSync(OUT_PATH, lines.join("\n"), "utf-8")
  console.log(`✓ Generated ${OUT_PATH}`)
  console.log(`  ${themeIds.length} themes, ${themeIds.length * 2} variants`)
}

generate()
